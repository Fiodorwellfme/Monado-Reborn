"""XCDE_SHADER_SIG: a fingerprint of the shader translation and SPIR-V compilation sources ([XCDE] T282).

cache/precompile_done.txt carries the fingerprint of the inputs a precompile ran with; `<game> --precompile-status
<dump>` (runtime/nvn/vulkan/precompile_sig.c) recomputes the current one and answers whether the precompiled cache
still matches it. Before this, the done stamp named the game executable's size and time, so every new build - even one
that only touched the launcher, the UI or gameplay code - precompiled all shaders again (a full warm run: the scan,
every translation and the driver pipeline creation).

The fingerprint covers the sources that decide what the precompiled artifacts are: the game-file discovery/read layer, the
Maxwell-to-GLSL translator, the GLSL replacement headers used by the build path, the GLSL-to-SPIR-V compiler with its cache
key and options, the precompile's own program/key guesses (new guesses mean new jobs to warm), the shader content hash the
precompile duplicates (runtime/nvn/objects.c) and the runtime acceptance of the precompiled SPIR-V
(runtime/cache_validation.h). It is a whole-file hash, comments included: any edit in those files costs one precompile run,
which is the conservative side of the choice. It does not cover the graphics driver (its shader caches are its own; press
"Precompile shaders" after a driver update) and it deliberately does not cover gameplay code: a runtime change that only
selects different jobs cannot invalidate what is already warm, it can only make the warm-up less complete until the next
translator change or an explicit run.

runtime/nvn/vulkan/exec.c's build path (vk_precompile_program / vk_precompile_variant / the pipeline library keys) is
also an input, but that file changes for gameplay too: it is covered by XCDE_PRECOMPILE_ARTIFACTS_REV in
runtime/nvn/vulkan/precompile_rev.h instead, which precompile_sig.c mixes into the signature. The embedded replacement
GLSL headers are hashed directly; the rest of exec.c is not. Bump the revision when what that path builds changes.

The build generates <build>/inc/shader_sig.h from this (CMake and the shell build scripts). A native test can compile
runtime/nvn/vulkan/precompile_sig.c with -DXCDE_SHADER_SIG="..." instead of generating it.
"""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# Sources whose change can change the precompiled shaders or the jobs that warm them (see the module docstring).
# The translator folder is fingerprinted whole (recursively): a new helper header or subfolder there belongs to it too.
TRANSLATOR_DIR = 'runtime/nvn/maxwell'
SOURCES = (
    # The scan reads extracted files or .nup packages through this layer; its title/tree selection decides the shader set.
    'runtime/services/game_files.c',
    'runtime/services/game_files.h',
    'runtime/nvn/vulkan/shaders.c',
    'runtime/nvn/vulkan/shaders.h',
    'runtime/nvn/vulkan/vk.h',
    'runtime/nvn/vulkan/precompile.c',
    # exec.c is revision-gated, but these headers supply the GLSL its precompile path embeds/replaces directly.
    'runtime/nvn/vulkan/bloom_prefilter.h',
    'runtime/nvn/vulkan/bloom.h',
    'runtime/nvn/vulkan/gtao.h',
    # [XCDE] T282 review: the content hash precompile.c duplicates (objects.c set_shaders) is what matches the seed /
    # variant records, and cache_validation.h decides whether the runtime accepts a precompiled SPIR-V entry.
    'runtime/nvn/objects.c',
    'runtime/cache_validation.h',
)


def sources(root=ROOT):
    """Every fingerprint input, sorted, as paths relative to the repository root."""
    files = {name for name in SOURCES if (root / name).is_file()}
    files.update(p.relative_to(root).as_posix() for p in (root / TRANSLATOR_DIR).rglob('*') if p.is_file())
    if (root / 'tools/build/shader_sig.py').is_file():
        files.add('tools/build/shader_sig.py')
    return sorted(files)


def fingerprint(root=ROOT):
    """16 hex digits: stable for a given game-file, translator, replacement-GLSL and compiler source set."""
    h = hashlib.sha256()
    for name in sources(root):
        h.update(name.encode())
        h.update(b'\0')
        h.update((root / name).read_bytes())
        h.update(b'\0')
    return h.hexdigest()[:16]


def header(root=ROOT):
    """The generated C header (<build>/inc/shader_sig.h)."""
    return ('// Generated by tools/build/shader_sig.py --out: do not edit. [XCDE] T282.\n'
            '// Fingerprint of the game-file discovery, shader translator/replacements and SPIR-V compiler sources:\n'
            '// cache/precompile_done.txt records it and `--precompile-status` compares it (precompile_sig.c).\n'
            '#pragma once\n'
            '#ifndef XCDE_SHADER_SIG\n'
            f'#define XCDE_SHADER_SIG "{fingerprint(root)}"\n'
            '#endif\n')


def main(argv=None):
    parser = argparse.ArgumentParser(description='Write the XCDE shader precompile fingerprint (T282).')
    parser.add_argument('--out', type=Path, help='C header to write (default: print the fingerprint)')
    parser.add_argument('--root', type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(header(args.root), encoding='utf-8')
    else:
        print(fingerprint(args.root))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
