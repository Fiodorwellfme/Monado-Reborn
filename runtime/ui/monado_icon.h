// Call before SDL_Init(SDL_INIT_VIDEO) so SDL3 registers its Win32 window class with our icon resource.
static inline void monado_prepare_window_icon_hints(void) {
#ifdef _WIN32
    SDL_SetHint(SDL_HINT_WINDOWS_INTRESOURCE_ICON, MONADO_WIN_ICON_ID_STR);
    SDL_SetHint(SDL_HINT_WINDOWS_INTRESOURCE_ICON_SMALL, MONADO_WIN_ICON_ID_STR);
#endif
}

static inline void monado_apply_window_icon_png(SDL_Window *w) {
    if (!w) return;
    SDL_IOStream *io = SDL_IOFromConstMem(k_monado_icon_png, sizeof(k_monado_icon_png));
    if (!io) return;
    SDL_Surface *s = SDL_LoadPNG_IO(io, true);
    if (s) {
        SDL_SetWindowIcon(w, s);
        SDL_DestroySurface(s);
    }
}

// Apply the Monado icon to an SDL3 window (taskbar, Alt-Tab, title bar).
static inline void monado_apply_window_icon(SDL_Window *w) {
    if (!w) return;
#ifdef _WIN32
    HWND hwnd = (HWND)SDL_GetPointerProperty(SDL_GetWindowProperties(w),
                                             SDL_PROP_WINDOW_WIN32_HWND_POINTER, NULL);
    if (hwnd) {
        HINSTANCE hinst = GetModuleHandleW(NULL);
        HICON big_icon = (HICON)LoadImageW(hinst, MAKEINTRESOURCEW(MONADO_WIN_ICON_ID), IMAGE_ICON,
                                           GetSystemMetrics(SM_CXICON), GetSystemMetrics(SM_CYICON),
                                           LR_DEFAULTCOLOR | LR_SHARED);
        HICON small_icon = (HICON)LoadImageW(hinst, MAKEINTRESOURCEW(MONADO_WIN_ICON_ID), IMAGE_ICON,
                                             GetSystemMetrics(SM_CXSMICON), GetSystemMetrics(SM_CYSMICON),
                                             LR_DEFAULTCOLOR | LR_SHARED);
        if (big_icon) SendMessageW(hwnd, WM_SETICON, ICON_BIG, (LPARAM)big_icon);
        if (small_icon) SendMessageW(hwnd, WM_SETICON, ICON_SMALL, (LPARAM)small_icon);
        if (big_icon || small_icon) return;
    }
#endif
    monado_apply_window_icon_png(w);
}

